const PressReleaseRow = ({ item, openModal }) => {
  const [open, setOpen] = useState(false);
  const hasContent =
    item.description || (item.images && item.images.length > 0);

  return (
    <>
      <tr
        onClick={() => {
          if (!item.noCollapse && hasContent) setOpen((prev) => !prev);
        }}
        style={{
          cursor: !item.noCollapse && hasContent ? "pointer" : "default",
          borderBottom: "1px solid #ddd",
        }}
      >
        <td style={{ padding: "8px" }}>{item.no}</td>
        <td style={{ padding: "8px" }}>{item.date}</td>
        <td style={{ padding: "8px" }}>
          {item.subject}
          {item.file && (
            <div>
              <a
                href={item.file}
                target="_blank"
                rel="noopener noreferrer"
                style={{ color: "blue", textDecoration: "none" }}
              >
                View PDF
              </a>
            </div>
          )}
        </td>
      </tr>

      {/* Collapsible Content */}
      {!item.noCollapse && hasContent && open && (
        <tr>
          <td colSpan={3} style={{ padding: 0, border: 0 }}>
            <motion.div
              initial={{ height: 0, opacity: 0 }}
              animate={{ height: "auto", opacity: 1 }}
              transition={{ duration: 0.3 }}
              style={{ overflow: "hidden" }}
            >
              <div style={{ padding: "10px", background: "#f9f9f9" }}>
                {/* Two small headings */}
                {item.heading1 && (
                  <h5
                    style={{
                      margin: "5px 0",
                      fontSize: "14px",
                      color: "#003366",
                    }}
                  >
                    {item.heading1}
                  </h5>
                )}
                {item.heading2 && (
                  <h6
                    style={{
                      margin: "5px 0",
                      fontSize: "12px",
                      color: "#003366",
                    }}
                  >
                    {item.heading2}
                  </h6>
                )}

                <p style={{ marginBottom: "10px" }}>{item.description}</p>

                <div
                  style={{
                    display: "flex",
                    flexWrap: "wrap",
                    gap: "10px",
                    justifyContent: "flex-start",
                  }}
                >
                  {item.images &&
                    item.images.map((img, index) => (
                      <div
                        key={index}
                        style={{
                          width: "200px",
                          height: "250px",
                          display: "flex",
                          justifyContent: "center",
                          alignItems: "center",
                          backgroundColor: "#fff",
                          overflow: "hidden",
                          borderRadius: "8px",
                          boxShadow: "0 1px 4px rgba(0,0,0,0.1)",
                          cursor: "pointer",
                        }}
                        onClick={() => openModal(item.images, index)}
                      >
                        <img
                          src={img}
                          alt={`press-${item.no}-${index}`}
                          style={{
                            maxWidth: "100%",
                            maxHeight: "100%",
                            objectFit: "contain", // ✅ keeps aspect ratio
                            borderRadius: "5px",
                          }}
                        />
                      </div>
                    ))}
                </div>
              </div>
            </motion.div>
          </td>
        </tr>
      )}
    </>
  );
};

